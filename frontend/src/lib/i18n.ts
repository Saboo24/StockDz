export function t(key: keyof typeof translations.fr, language: Language = DEFAULT_LANGUAGE) {
  return translations[language][key] ?? translations[DEFAULT_LANGUAGE][key] ?? key
}

export function formatCurrency(value: number | string) {
  const numeric = Number(value ?? 0)
  return `${Number.isFinite(numeric) ? numeric.toLocaleString('fr-DZ') : '0'} DZA`
}
